/**
 * Generates config/headers.json - the single source of truth for the site's
 * security headers, read by Terraform (the CloudFront response headers
 * policy) and by scripts/preview.mjs (the local production check).
 *
 *   node scripts/gen-headers.mjs           write config/headers.json
 *   node scripts/gen-headers.mjs --check   exit 1 if it is stale
 *
 * Runs against a finished build: the CSP's style hashes come from the
 * inline <style> blocks in site/dist, and its third-party origins from the
 * analytics entry in site/src/config/site.ts, plus Turnstile's for the
 * contact form. Build first.
 *
 * Any inline style="" attribute in the build is an error, not a hash: the
 * policy has no 'unsafe-hashes', so the browser would drop it.
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { analytics } from '../site/src/config/site.ts';
import { buildHeaders, collectInlineStyles } from './lib/csp.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const distDir = join(root, 'site', 'dist');
export const headersPath = join(root, 'config', 'headers.json');

async function htmlFiles(dir) {
  const entries = await readdir(dir, { withFileTypes: true, recursive: true });
  return entries
    .filter((entry) => entry.isFile() && entry.name.endsWith('.html'))
    .map((entry) => join(entry.parentPath, entry.name))
    .sort();
}

/** The headers.json text the current build calls for. */
export async function generate() {
  let files;
  try {
    files = await htmlFiles(distDir);
  } catch {
    files = [];
  }
  if (files.length === 0) {
    throw new Error(`No HTML found in ${relative(root, distDir)}/ - run npm run build first.`);
  }

  const blocks = [];
  const attributes = new Map();
  for (const file of files) {
    const found = collectInlineStyles(await readFile(file, 'utf8'));
    blocks.push(...found.blocks);
    for (const value of found.attributes) {
      if (!attributes.has(value)) attributes.set(value, relative(root, file));
    }
  }

  if (attributes.size > 0) {
    const found = [...attributes].map(([value, file]) => `  style="${value}" (first in ${file})`);
    throw new Error(
      `Inline style attributes in the build, which the CSP would block:\n${found.join('\n')}\n` +
        'Use a class instead. Code blocks map Shiki styles in site/src/lib/shiki-classes.ts.',
    );
  }

  // One policy covers every page, so the contact page's Turnstile origin is
  // allowed site-wide; only that page loads it.
  const headers = buildHeaders({ blocks, analytics, turnstile: true });

  return `${JSON.stringify(
    {
      $comment:
        'Generated by scripts/gen-headers.mjs from the build and site/src/config/site.ts. Do not edit; run npm run headers.',
      ...headers,
    },
    null,
    2,
  )}\n`;
}

async function main() {
  const check = process.argv.includes('--check');
  const expected = await generate();

  let current = null;
  try {
    current = await readFile(headersPath, 'utf8');
  } catch {
    // Missing counts as stale.
  }

  if (check) {
    if (current !== expected) {
      console.error(
        'config/headers.json is stale for this build. Run `npm run headers` and commit the result.\n' +
          'Only the inline <style> blocks change it: the committed font files or their configuration.',
      );
      process.exitCode = 1;
      return;
    }
    console.log('config/headers.json is up to date.');
    return;
  }

  if (current === expected) {
    console.log('config/headers.json unchanged.');
    return;
  }
  await writeFile(headersPath, expected);
  console.log(`Wrote ${relative(root, headersPath)}.`);
}

// Only run when invoked directly; preview.mjs imports generate() to check
// freshness without writing anything.
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
